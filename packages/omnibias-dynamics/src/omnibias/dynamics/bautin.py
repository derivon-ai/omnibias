r"""The Bautin (focal-value) ideal, its Groebner basis, and center membership.

:mod:`omnibias.dynamics.focal` computes each Poincare-Lyapunov focal value
``V_k`` as a :class:`~omnibias.holonomic._core.poly_n.PolyN` in the field's
symbolic parameters. The **ideal** ``(V_1, ..., V_N)`` those quantities
generate is gauge-invariant (unlike any single ``V_k`` beyond the first
nonzero one, see the honesty note in :mod:`omnibias.dynamics.focal`) and its
zero set is exactly the (truncated) center variety: a parameter point makes
*every* focal value vanish -- and hence, by the classical Poincare-Lyapunov
theorem plus (for the quadratic family) Bautin's finiteness theorem, is a
genuine center -- iff it lies in this variety.

This module computes the ideal's :func:`bautin_basis` with the exact-``Q``
Buchberger engine in :mod:`omnibias.holonomic._core.groebner` and answers
:func:`center_membership` queries against it, both with exact cofactor
witnesses. **What this module does not do:** it does not re-derive or assert
Bautin's theorem that three focal values already generate the full ideal for
the quadratic family -- ``bautin_basis`` reports whatever the Groebner basis
of the *supplied, truncated* generator list happens to be, and
``cyclicity_bound = basis_length - 1`` is always reported alongside
``bautin_ideal_stabilization_proved = False``. Confirming that supplying a
4th, 5th, ... generator never enlarges the ideal is exactly the
un-formalized mathematical content of Bautin's theorem; this module gives you
the machinery to *check* finite-order stabilization on any concrete instance,
not a proof that it holds in general.
"""

