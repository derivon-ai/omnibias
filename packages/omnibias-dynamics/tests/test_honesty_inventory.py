from __future__ import annotations

from omnibias.dynamics.honesty_inventory import build_honesty, inventory_report


def test_build_honesty_attaches_reasons_for_false_flags() -> None:
    payload = build_honesty(full_hilbert16_solved=False, g1_passed=False)
    assert payload["full_hilbert16_solved"] is False
    reasons = payload["_honesty_reasons"]
    assert reasons["full_hilbert16_solved"]["reason"] == "derived_false"
    assert reasons["g1_passed"]["reason"] == "gate_open"


