"""Certified fluid-dynamics validation artifacts.

Rigorous, replayable validation for incompressible-flow candidates: theorem
contracts, honesty labels, periodic spectral residual checks, certified-artifact
(CAP) bundles, and explicit proof obligations for Navier-Stokes, Euler-2D and
surface quasi-geostrophic flow.  The core is intentionally backend-neutral and
does not import JAX or Torch.

Scope.  Everything here bounds a *discrete, finite* object: a residual on a fixed
grid, an enclosure over a fixed box, a rollout over a fixed horizon.  Global
regularity of the continuum equations is an open problem, and nothing in this
module asserts anything about it -- see :mod:`omnibias.pinn.certified.machine`
for the gate that blocks such a claim from ever being emitted.
"""

