def _sample_sine_ics(
    n_samples: int,
    x: np.ndarray,
    *,
    n_modes: int,
    amplitude: float,
    seed: int,
) -> np.ndarray:
    """Dirichlet-compatible sine modes on ``[0, L]`` (``u(0)=u(L)=0``)."""
    rng = np.random.default_rng(seed)
    L = float(x[-1])
    out = np.zeros((n_samples, x.size), dtype=float)
    for f in range(n_samples):
        for k in range(1, n_modes + 1):
            out[f] += rng.uniform(-amplitude, amplitude) * np.sin(k * np.pi * x / L)
    return out


def _dirichlet_heat_rhs(u: Tensor, diffusivity: float, dx: float) -> Tensor:
    du = torch.zeros_like(u)
    du[1:-1] = float(diffusivity) * (u[2:] - 2.0 * u[1:-1] + u[:-2]) / (dx * dx)
    return du


def _dirichlet_burgers_rhs(u: Tensor, viscosity: float, dx: float) -> Tensor:
    du = torch.zeros_like(u)
    ux = (u[2:] - u[:-2]) / (2.0 * dx)
    uxx = (u[2:] - 2.0 * u[1:-1] + u[:-2]) / (dx * dx)
    du[1:-1] = -u[1:-1] * ux + float(viscosity) * uxx
    return du


def _march_dirichlet(
    u0: Tensor,
    rhs_fn: Callable[[Tensor], Tensor],
    times: Tensor,
    *,
    dx: float,
) -> Tensor:
    """Explicit RK4 march with pinned endpoints."""
    snaps = [u0.clone()]
    u = u0.clone()
    u[0] = 0.0
    u[-1] = 0.0
    for ti in range(1, times.numel()):
        dt = float(times[ti] - times[ti - 1])
        k1 = rhs_fn(u)
        k2 = rhs_fn(u + 0.5 * dt * k1)
        k3 = rhs_fn(u + 0.5 * dt * k2)
        k4 = rhs_fn(u + dt * k3)
        u = u + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
        u[0] = 0.0
        u[-1] = 0.0
        snaps.append(u.clone())
    return torch.stack(snaps, dim=0)


def _nonperiodic_space_time_coords(x: Tensor, times: Tensor) -> Tensor:
    xs = x.repeat(times.numel())
    ts = times.repeat_interleave(x.numel())
    return torch.stack([xs, ts], dim=-1)


def make_nonperiodic_parametric_heat_slab(
    *,
    n_samples: int = 8,
    n_grid: int = 64,
    n_sensors: int = 16,
    n_modes: int = 3,
    amplitude: float = 0.5,
    length: float = 1.0,
    diffusivities: tuple[float, ...] | None = None,
    diffusivity_range: tuple[float, float] = (0.05, 0.2),
    t_final: float = 0.2,
    n_times: int = 6,
    seed: int = 0,
    dtype: torch.dtype = torch.float64,
) -> ParametricOperatorSlab:
    """Non-periodic heat on ``[0, L]`` with homogeneous Dirichlet BC."""
    rng = np.random.default_rng(seed)
    if diffusivities is None:
        lo, hi = diffusivity_range
        diffs = rng.uniform(lo, hi, size=n_samples)
    else:
        diffs = np.asarray(diffusivities, dtype=float)
    x_np = np.linspace(0.0, float(length), n_grid, endpoint=False)
    u0_np = _sample_sine_ics(
        n_samples, x_np, n_modes=n_modes, amplitude=amplitude, seed=seed
    )
    x = torch.tensor(x_np, dtype=dtype)
    u0 = torch.tensor(u0_np, dtype=dtype)
    dx = float(length / n_grid)
    idx = torch.linspace(0, n_grid, steps=n_sensors + 1, dtype=torch.long)[:-1]
    sensors = u0[:, idx]
    times = torch.linspace(0.0, t_final, n_times, dtype=dtype)
    snaps_list = []
    for i in range(n_samples):
        D = float(diffs[i])

        def rhs(u: Tensor, *, _D: float = D) -> Tensor:
            return _dirichlet_heat_rhs(u, _D, dx)

        snaps_list.append(_march_dirichlet(u0[i], rhs, times, dx=dx))
    snaps_b = torch.stack(snaps_list, dim=0)
    grid = SpectralGrid1D(n_grid, float(length), dtype=dtype)
    coords = _nonperiodic_space_time_coords(x, times)
    values = snaps_b.reshape(n_samples, -1, 1)
    parameters = torch.tensor(diffs.reshape(n_samples, 1), dtype=dtype)
    return ParametricOperatorSlab(
        sensors=sensors,
        coords=coords,
        values=values,
        grid=grid,
        parameters=parameters,
    )


