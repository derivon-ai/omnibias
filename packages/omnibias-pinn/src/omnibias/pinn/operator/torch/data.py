"""Operator-learning datasets from the existing spectral MOL reference (torch).

No new solver: pairs ``(u_0, u(., t))`` are generated by
:func:`~omnibias.pinn.solver.torch.evolution.method_of_lines` on a
:class:`~omnibias.pinn.solver.torch.spectral.SpectralGrid1D`.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

import numpy as np
import torch
from omnibias.pinn.operator._core.sensors import SensorGrid, sample_fourier_ics
from omnibias.pinn.solver.torch.evolution import (
    burgers_semidiscrete,
    heat_semidiscrete,
    kuramoto_sivashinsky_semidiscrete,
    method_of_lines,
)
from omnibias.pinn.solver.torch.spectral import SpectralGrid1D
from torch import Tensor


@dataclass(frozen=True)
class OperatorSlab:
    """A batch of space-time solution slabs for operator learning.

    Attributes
    ----------
    sensors
        Input-function observations of shape ``(F, m)``.
    coords
        Query coordinates of shape ``(Q, D)`` with axes ``(x, t)`` (or the
        problem's coordinate order). Shared across the batch.
    values
        Target field values of shape ``(F, Q, C)``.
    grid
        The spectral grid the reference was marched on.
    """

    sensors: Tensor
    coords: Tensor
    values: Tensor
    grid: SpectralGrid1D


def _space_time_coords(grid: SpectralGrid1D, times: Tensor) -> Tensor:
    """Build the shared ``(Q, 2)`` query grid with columns ``(x, t)``."""
    x = grid.points()  # (n,)
    # Full product: for each time, every x.
    xs = x.repeat(times.numel())
    ts = times.repeat_interleave(x.numel())
    return torch.stack([xs, ts], dim=-1)


def _assert_heat_maximum_principle(
    snaps: Tensor,
    u0: Tensor,
    *,
    name: str,
) -> None:
    """Enforce the heat maximum principle ``max|u(t)| <= max|u0|``.

    Explicit RK4 on a stiff Fourier heat operator can produce finite-but-
    exploding snapshots that pass an ``isfinite`` check while encoding a
    divergence (measured: ``max|u| ~ 1e9`` at diffusivity 0.24). The
    physical invariant catches that class of failure.
    """
    if not torch.isfinite(snaps).all():
        raise RuntimeError(
            f"{name}: non-finite values; reduce amplitude / n_modes "
            "or use an unconditionally stable integrator"
        )
    u0_max = float(u0.detach().abs().amax())
    snaps_max = float(snaps.detach().abs().amax())
    if snaps_max > u0_max * (1.0 + 1e-6) + 1e-12:
        raise RuntimeError(
            f"{name}: maximum principle violated "
            f"(max|u|={snaps_max:.3e} > max|u0|={u0_max:.3e}); "
            "the reference integrator is unstable -- use etdrk4 for heat"
        )


def make_heat_slab(
    *,
    n_samples: int = 32,
    n_grid: int = 64,
    n_sensors: int = 32,
    n_modes: int = 4,
    amplitude: float = 1.0,
    diffusivity: float = 0.1,
    t_final: float = 0.5,
    n_times: int = 11,
    seed: int = 0,
    dtype: torch.dtype = torch.float64,
) -> OperatorSlab:
    """Periodic heat equation slabs from spectral MOL + analytic-mode ICs."""
    length = 2.0 * torch.pi
    grid = SpectralGrid1D(n_grid, float(length), dtype=dtype)
    # Sample ICs on the fine grid, then restrict to sensors.
    fine = SensorGrid(points=grid.points().detach().cpu().numpy(), length=float(length))
    u0_np = sample_fourier_ics(
        n_samples, fine, n_modes=n_modes, amplitude=amplitude, seed=seed
    )
    u0 = torch.tensor(u0_np, dtype=dtype)
    # Sensor observations by nearest-neighbour on the fine grid (equispaced, so
    # exact subsample when n_sensors divides n_grid).
    idx = torch.linspace(0, n_grid, steps=n_sensors + 1, dtype=torch.long)[:-1]
    sensors = u0[:, idx]
    times = torch.linspace(0.0, t_final, n_times, dtype=dtype)
    times_seq = [float(t) for t in times]
    # Heat is linear with a diagonal Fourier symbol; ETDRK4 advances it by
    # exp(dt L) exactly and is unconditionally stable. Explicit RK4 crosses
    # its stability boundary around diffusivity ~0.14 on a 64-point grid.
    semi = heat_semidiscrete(grid, diffusivity)
    snaps_list = []
    for i in range(n_samples):
        snaps, _ = method_of_lines(semi, u0[i], times_seq, integrator="etdrk4")
        snaps_list.append(snaps)  # (T, n)
    snaps_b = torch.stack(snaps_list, dim=0)  # (F, T, n)
    _assert_heat_maximum_principle(snaps_b, u0, name="heat MOL reference")
    coords = _space_time_coords(grid, times)
    # values (F, T*n, 1)
    values = snaps_b.reshape(n_samples, -1, 1)
    return OperatorSlab(sensors=sensors, coords=coords, values=values, grid=grid)


